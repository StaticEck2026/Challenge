#!/usr/bin/env python3
"""Static recompiler: NFL.EXE (8086, PLINK86 overlays) -> GDScript.

  python3 -I tools/recomp/recompile.py /path/to/NFL.EXE [--out godot/recomp]
  python3 -I tools/recomp/recompile.py /path/to/game-folder      # NFL.EXE and SEASON.COM
  python3 -I tools/recomp/recompile.py NFL.EXE SEASON.COM

Reads only the user's own NFL.EXE, plus two small address-only inputs that
ship with the translator: tools/recomp/profile.json (dynamic control-flow
targets observed by running the Python oracle, see profile_oracle.py) and
tools/recomp/hints.json (address-keyed translation hints with evidence).

Writes godot/recomp/ (gitignored: the output is derived from the copyrighted
binary and must never be committed):
  u_*.gd          one script per group of functions (root segments / overlays)
  recomp_index.gd unit list, entry point, the dispatch table, PROGRAM_SHA1
  program.bin     the program image the run time needs instead of NFL.EXE:
                  MZ header values, the root image relocated for load segment
                  0122h, and the overlay section of the file (read by the
                  native overlay manager through a virtual file)
  season/         the same for SEASON.COM (a .COM program has its own units,
                  index and program.bin in godot/recomp/<name>/)
  game/           with --bundle-data: the game's data files (everything in the
                  EXE's folder except programs), for a standalone export
and build/recomp/manifest.json (translated instruction addresses, used by the
coverage report).
"""
import argparse
import hashlib
import json
import os
import shutil
import struct
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import analysis  # noqa: E402
import gdgen  # noqa: E402
import image  # noqa: E402

FILE_LINES = 40000          # soft limit of lines per generated script


# gdlint settings for the generated scripts: machine-written code has huge
# files and functions, many locals and returns, and long lines.
GDLINTRC = """# Generated by tools/recomp/recompile.py: relaxed limits for generated code.
disable:
- max-file-lines
- max-line-length
- max-returns
- max-public-methods
- function-variable-name
- class-variable-name
- no-elif-return
- no-else-return
- unnecessary-pass
- duplicated-load
- function-name
"""


def load_profile(paths):
    """(transfers, returns) merged from coverage profile files."""
    out, ret = [], []
    for p in paths:
        if os.path.exists(p):
            with open(p) as f:
                d = json.load(f)
            out.extend(d["transfers"])
            ret.extend(d.get("returns", []))
    return out, ret


def static_far_pointers(prog):
    """Far code pointers stored in the initialised data segment (overlay 12):
    a relocated segment word whose value is a root code segment, preceded by an
    offset.  They are function-pointer targets (dispatcher entries) whether or
    not the profiling runs called them."""
    o = prog.ovl[12]
    img = o["data"]
    seg0 = o["info"].seg_start
    out = set()
    _, rel = prog.exe.overlay_bytes(o["info"])
    for off, seg in rel:
        a = (seg - seg0) * 16 + off
        if a < 2 or a + 2 > len(img):
            continue
        v = img[a] | (img[a + 1] << 8)
        lo = img[a - 2] | (img[a - 1] << 8)
        lin = ((v << 4) + lo) & 0xFFFFF
        if prog.root_lin <= lin < prog.root_end and v < prog.table_seg:
            out.add((v, lo))
    return sorted(out)


def unit_num(unit):
    return 0 if unit == "root" else unit


def entry_key(prog):
    if prog.kind == "com":
        return ("root", prog.cs, 0x0100)
    return ("root", 0x13F3 + prog.base, 0x0007)


def build(exe, profile_paths, hints_path, log=print):
    prog = image.load_program(exe)
    profile, returns = load_profile(profile_paths)
    hints = {}
    if hints_path is None:
        hints_path = default_hints(exe)
    if hints_path and os.path.exists(hints_path):
        hints = analysis.load_json(hints_path)       # address-keyed for this exact program
    an = analysis.Analysis(prog, profile, hints, log, returns)
    if prog.kind == "com":
        an.add_entry(entry_key(prog), "COM entry PSP:0100")
    else:
        an.add_entry(entry_key(prog), "C start-up (entered by the native overlay-manager start-up)")
        for t in prog.thunks:
            an.add_entry((t["ovl"], t["tseg"], t["toff"]), "overlay thunk %04X:%04X" % (t["cs"], t["ip"]))
        for seg, off in static_far_pointers(prog):
            an.add_entry((prog.unit_of(((seg << 4) + off) & 0xFFFFF, "root"), seg, off),
                         "profile-like: static far pointer in DGROUP")
    an.run()
    if an.apply_ret_hints():
        an.funcs = {}
        an.run()
    # dispatcher entries and functions that can return past their caller
    # (stack unwinding) must leave every flag in the CPU state
    dyn_entries = {k for k, why in an.entries if why.startswith("profile")}
    unwind_sites = set()
    for t in profile:
        if "unwind" in t["kind"]:
            cs, ip = (int(x, 16) for x in t["site"].split(":"))
            unwind_sites.add((cs, ip))
    for f in an.funcs.values():
        f.fout_min = 0
        if f.key in dyn_entries:
            f.fout_min = analysis.ALL
        if any((f.cs, ip) in unwind_sites for ip in f.insns):
            f.fout_min = analysis.ALL
    an.compute_regs()
    an.compute_flags()
    return prog, an


def group_files(an):
    """Assign functions to generated scripts: root by segment ranges, overlays per overlay."""
    groups = {}
    for f in sorted(an.funcs.values(), key=lambda f: (unit_num(f.unit), f.cs, f.ip)):
        groups.setdefault(f.unit, []).append(f)
    files = []
    for unit, fl in sorted(groups.items(), key=lambda kv: unit_num(kv[0])):
        cur = []
        size = 0
        idx = 0
        for f in fl:
            est = sum(len(b.insns) for b in f.blocks.values()) * 7 + 20
            if cur and size + est > FILE_LINES:
                files.append(("u_%s_%d" % (analysis.unit_tag(unit), idx), cur))
                idx += 1
                cur, size = [], 0
            cur.append(f)
            size += est
        if cur:
            files.append(("u_%s_%d" % (analysis.unit_tag(unit), idx), cur))
    for name, fl in files:
        for f in fl:
            f.file = name
    return files


def generate(prog, an, out_dir, comments=False, log=print):
    gdgen.COMMENTS = comments
    os.makedirs(out_dir, exist_ok=True)
    for n in os.listdir(out_dir):
        if n.endswith(".gd") or n.endswith(".gd.uid"):
            os.remove(os.path.join(out_dir, n))
    files = group_files(an)
    total_lines = 0
    for name, fl in files:
        def unit_ref(g, name=name):
            return "" if g.file == name else "%s." % g.file
        body = []
        refs = set()
        for f in fl:
            lines = gdgen.gen_function(an, f, unit_ref)
            for ins, kind, ck in f.calls:
                g = an.funcs.get(ck)
                if g is not None and g.file != name:
                    refs.add(g.file)
            body.append("\n".join(lines))
        head = ["# Generated by tools/recomp/recompile.py from the user's NFL.EXE -- do not edit,",
                "# do not commit (derived from copyrighted code).",
                "extends RecompUnit", ""]
        for r in sorted(refs):
            head.append("var %s = null" % r)
        head.append("")
        head.append("")
        head.append("func _link(%s: Dictionary) -> void:" % ("units" if refs else "_units"))
        if refs:
            for r in sorted(refs):
                head.append("\t%s = units[\"%s\"]" % (r, r))
        else:
            head.append("\tpass")
        head.append("")
        text = "\n".join(head) + "\n\n" + "\n\n\n".join(body) + "\n"
        total_lines += text.count("\n")
        with open(os.path.join(out_dir, name + ".gd"), "w") as fp:
            fp.write(text)
    # index: units, entry, dispatch table
    idx = ["# Generated by tools/recomp/recompile.py -- do not edit, do not commit.",
           "extends RefCounted", "",
           "const LOAD_SEG := 0x%X" % prog.base,
           "const UNITS := [%s]" % ", ".join('"%s"' % n for n, _ in files)]
    entry = an.funcs[entry_key(prog)]
    idx.append('const KIND := "%s"' % prog.kind)
    idx.append('const PROGRAM_SHA1 := "%s"' % write_program_blob(prog, out_dir))
    idx.append('const ENTRY_UNIT := "%s"' % entry.file)
    idx.append('const ENTRY_FUNC := "%s"' % entry.name)
    idx.append("const FUNCTIONS := %d" % len(an.funcs))
    idx.append("")
    idx.append("")
    idx.append("## key = (unit << 40) | (cs << 16) | ip ; unit 0 = root, n = overlay n")
    idx.append("static func dispatch_table() -> Dictionary:")
    idx.append("\treturn {")
    for f in sorted(an.funcs.values(), key=lambda f: (unit_num(f.unit), f.cs, f.ip)):
        k = (unit_num(f.unit) << 40) | (f.cs << 16) | f.ip
        idx.append('\t\t0x%X: ["%s", "%s"],' % (k, f.file, f.name))
    idx.append("\t}")
    with open(os.path.join(out_dir, "recomp_index.gd"), "w") as fp:
        fp.write("\n".join(idx) + "\n")
    with open(os.path.join(out_dir, "gdlintrc"), "w") as fp:
        fp.write(GDLINTRC)
    log("[recomp] %d functions, %d instructions, %d blocks -> %d scripts, %d lines in %s" % (
        len(an.funcs), sum(len(f.insns) for f in an.funcs.values()),
        sum(len(f.blocks) for f in an.funcs.values()), len(files), total_lines, out_dir))
    return files


BLOB_MAGIC = b"NFLRCMP1"


def write_program_blob(prog, out_dir):
    """program.bin (layout documented in godot/host/program_blob.gd)."""
    if prog.kind == "com":
        data = prog.data
        sha = hashlib.sha1(data).digest()
        name = os.path.basename(prog.exe_path).upper().encode("ascii", "replace")[:15]
        head = b"NFLRCOM1" + sha + struct.pack("<8H4I", prog.base, 0, 0x100, 0, 0xFFFE, 0, 0, 0,
                                               len(data), len(data), len(data), 0)
        head += name.ljust(16, b"\0")
        with open(os.path.join(out_dir, "program.bin"), "wb") as fp:
            fp.write(head + data)
        return sha.hex()
    e = prog.exe
    h = e.hdr
    data = e.data
    sha = hashlib.sha1(data).digest()
    ovl = data[e.image_end:]
    name = os.path.basename(prog.exe_path).upper().encode("ascii", "replace")[:15]
    head = BLOB_MAGIC + sha + struct.pack("<8H4I", prog.base, h.cs, h.ip, h.ss, h.sp, h.minalloc,
                                          h.maxalloc, h.crlc, len(prog.root), len(data), e.image_end,
                                          len(ovl))
    head += name.ljust(16, b"\0")
    assert len(head) == 76
    with open(os.path.join(out_dir, "program.bin"), "wb") as fp:
        fp.write(head + prog.root + ovl)
    return sha.hex()


PROGRAM_EXTS = (".EXE", ".COM", ".BAT", ".WHL")


def bundle_data(exe, out_dir, log=print):
    """Copy the game's data files (the EXE's folder minus programs) to out_dir/game."""
    src = os.path.dirname(os.path.abspath(exe))
    dst = os.path.join(out_dir, "game")
    if os.path.exists(dst):
        shutil.rmtree(dst)
    n = size = 0
    for dp, dn, fn in os.walk(src):
        dn[:] = sorted(d for d in dn if not d.startswith("."))
        rel = os.path.relpath(dp, src)
        for f in sorted(fn):
            if f.upper().endswith(PROGRAM_EXTS) or f.startswith("."):
                continue
            os.makedirs(os.path.join(dst, rel), exist_ok=True)
            shutil.copy2(os.path.join(dp, f), os.path.join(dst, rel, f))
            n += 1
            size += os.path.getsize(os.path.join(dp, f))
    log("[recomp] --bundle-data: %d data files (%d KB) -> %s" % (n, size // 1024, dst))


def write_manifest(prog, an, path):
    funcs = []
    for f in an.funcs.values():
        funcs.append({"unit": unit_num(f.unit), "cs": f.cs, "ip": f.ip, "name": f.name, "file": f.file,
                      "insns": sorted(((f.cs << 4) + ip) & 0xFFFFF for ip in f.insns),
                      "sizes": {str(((f.cs << 4) + ip) & 0xFFFFF): i.size for ip, i in f.insns.items()}})
    data = {"load_seg": prog.base, "functions": funcs, "warnings": an.warnings,
            "ovl": {str(n): [o["start"], o["end"]] for n, o in prog.ovl.items()},
            "root": [prog.root_lin, prog.root_end]}
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fp:
        json.dump(data, fp)


def find_programs(paths):
    """Inputs -> [program file]: a folder means its NFL.EXE and SEASON.COM."""
    out = []
    for p in paths:
        if os.path.isdir(p):
            names = {n.upper(): n for n in os.listdir(p)}
            for want in ("NFL.EXE", "SEASON.COM"):
                if want in names:
                    out.append(os.path.join(p, names[want]))
        else:
            out.append(p)
    return out


def out_dir_for(prog_path, base_out):
    """NFL.EXE (or any MZ program) -> base_out; a .COM program -> base_out/<name>."""
    with open(prog_path, "rb") as f:
        mz = f.read(2) in (b"MZ", b"ZM")
    if mz:
        return base_out
    return os.path.join(base_out, os.path.splitext(os.path.basename(prog_path))[0].lower())


def default_hints(prog_path):
    with open(prog_path, "rb") as f:
        mz = f.read(2) in (b"MZ", b"ZM")
    if mz:
        return os.path.join(HERE, "hints.json")
    return os.path.join(HERE, "hints_%s_com.json" % os.path.splitext(os.path.basename(prog_path))[0].lower())


def default_profile(prog_path):
    with open(prog_path, "rb") as f:
        mz = f.read(2) in (b"MZ", b"ZM")
    if mz:
        return os.path.join(HERE, "profile.json")
    return os.path.join(HERE, "profile_%s_com.json" % os.path.splitext(os.path.basename(prog_path))[0].lower())


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inputs", nargs="+",
                    help="NFL.EXE and/or SEASON.COM, or the game folder (both programs)")
    ap.add_argument("--out", default=os.path.join(ROOT, "godot", "recomp"))
    ap.add_argument("--profile", action="append", default=None,
                    help="coverage profile(s) (default: tools/recomp/profile.json for NFL.EXE, "
                         "profile_season_com.json for SEASON.COM)")
    ap.add_argument("--hints", default=None,
                    help="hints file (default: tools/recomp/hints.json for NFL.EXE, "
                         "hints_season_com.json for SEASON.COM)")
    ap.add_argument("--manifest", default=os.path.join(ROOT, "build", "recomp", "manifest.json"))
    ap.add_argument("--comments", action="store_true", help="annotate every instruction in the output")
    ap.add_argument("--bundle-data", action="store_true",
                    help="also copy the game's data files to <out>/game (standalone export)")
    a = ap.parse_args(argv)
    t0 = time.time()
    progs = find_programs(a.inputs)
    if not progs:
        ap.error("no NFL.EXE / SEASON.COM found in %s" % a.inputs)
    for path in progs:
        out = out_dir_for(path, a.out)
        os.makedirs(out, exist_ok=True)
        profiles = a.profile or [default_profile(path)]
        prog, an = build(path, profiles, a.hints)
        for w in an.warnings:
            print("[warn] " + w, file=sys.stderr)
        print("[recomp] %s -> %s" % (os.path.basename(path), out))
        generate(prog, an, out, a.comments)
        man = a.manifest
        if prog.kind == "com":
            man = os.path.join(os.path.dirname(a.manifest), "manifest_%s.json" % os.path.basename(out))
        write_manifest(prog, an, man)
    if a.bundle_data:
        bundle_data(progs[0], a.out)
    print("[recomp] done in %.1fs" % (time.time() - t0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
